//! Dotfile collections (ADR-0019).
//!
//! A collection is a folder under [`paths::dotfiles_dir`] holding files for
//! `/root`: plain files, copied as they are, and optionally a top-level
//! `default.nix` that generates more. `create --dotfiles a,b` merges the named
//! collections in order (later ones win, with a warning) and writes the result
//! into the VM's data dir; every start puts that copy on the config disk.
//!
//! Plain files never touch the Nix store, which is what makes them the place
//! for credentials. A `default.nix` is only evaluated, never built.

use std::collections::BTreeMap;
use std::fs;
use std::io;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::paths;

/// The evaluator for a collection's `default.nix`, embedded from the repo.
const EVAL_NIX: &str = include_str!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../nix/dotfiles.nix"
));

/// Environment override for the `nix-instantiate` binary.
const NIX_INSTANTIATE_ENV: &str = "SODABOX_NIX_INSTANTIATE";

/// The file a collection may use to generate files.
pub const GENERATOR: &str = "default.nix";

/// Where a file's content comes from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Content {
    /// A plain file in the collection, copied byte for byte.
    Plain(PathBuf),
    /// Text generated by the collection's `default.nix`.
    Text(String),
}

/// One file of a collection or of a merged tree.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Entry {
    pub content: Content,
    /// Permission bits (`0o777` at most).
    pub mode: u32,
    /// The collection that supplied it.
    pub collection: String,
}

/// A loaded collection: its files by path relative to `/root`.
#[derive(Debug, Clone)]
pub struct Collection {
    pub name: String,
    pub files: BTreeMap<String, Entry>,
}

/// Collections merged in order, with one warning per replaced file.
#[derive(Debug, Clone, Default)]
pub struct Merged {
    pub files: BTreeMap<String, Entry>,
    pub warnings: Vec<String>,
}

/// A collection name: the profile rule (ADR-0015), since it is a folder name.
pub fn validate_name(name: &str) -> Result<(), String> {
    crate::profile::validate_name(name).map_err(|_| {
        format!(
            "invalid dotfile collection name '{name}': use lowercase letters, digits, '-' and '_'"
        )
    })
}

/// A path under `/root`: relative, `/`-separated, no empty, `.` or `..` parts.
pub fn validate_path(path: &str) -> Result<(), String> {
    let ok = !path.is_empty()
        && !path.starts_with('/')
        && path
            .split('/')
            .all(|p| !p.is_empty() && p != "." && p != "..");
    if ok {
        Ok(())
    } else {
        Err(format!(
            "invalid dotfile path '{path}': must be relative, without '.' or '..'"
        ))
    }
}

/// Parse an octal mode such as `"0600"`; at most `0o777`.
fn parse_mode(mode: &str) -> Result<u32, String> {
    u32::from_str_radix(mode, 8)
        .ok()
        .filter(|m| *m <= 0o777)
        .ok_or_else(|| format!("invalid mode '{mode}': use octal permission bits such as \"0600\""))
}

/// Load collection `name` from [`paths::dotfiles_dir`]. A `default.nix` is
/// evaluated against the pinned nixpkgs of `guest_dir` (ADR-0012).
pub fn load(name: &str, guest_dir: &Path) -> Result<Collection, String> {
    validate_name(name)?;
    load_from(&paths::dotfiles_dir().join(name), name, |dir| {
        eval_generator(dir, guest_dir)
    })
}

/// [`load`] from an explicit folder, with the `default.nix` evaluator passed in
/// (hermetic; tests).
pub fn load_from(
    dir: &Path,
    name: &str,
    eval: impl FnOnce(&Path) -> Result<BTreeMap<String, (String, u32)>, String>,
) -> Result<Collection, String> {
    if !dir.is_dir() {
        return Err(format!(
            "unknown dotfile collection '{name}' (no folder at {})",
            dir.display()
        ));
    }
    let mut files = BTreeMap::new();
    scan_plain(dir, dir, name, &mut files)
        .map_err(|e| format!("dotfile collection '{name}': {e}"))?;
    if dir.join(GENERATOR).is_file() {
        for (path, (text, mode)) in eval(dir)? {
            validate_path(&path).map_err(|e| format!("dotfile collection '{name}': {e}"))?;
            if files.contains_key(&path) {
                return Err(format!(
                    "dotfile collection '{name}': `{path}` is both a plain file and generated by {GENERATOR}"
                ));
            }
            files.insert(
                path,
                Entry {
                    content: Content::Text(text),
                    mode,
                    collection: name.to_string(),
                },
            );
        }
    }
    Ok(Collection {
        name: name.to_string(),
        files,
    })
}

/// Walk the plain files of a collection. Only regular files and folders are
/// allowed; a symlink could pull in anything on the host.
fn scan_plain(
    root: &Path,
    dir: &Path,
    name: &str,
    out: &mut BTreeMap<String, Entry>,
) -> Result<(), String> {
    let entries = fs::read_dir(dir).map_err(|e| format!("reading {}: {e}", dir.display()))?;
    for entry in entries {
        let entry = entry.map_err(|e| format!("reading {}: {e}", dir.display()))?;
        let path = entry.path();
        if dir == root && entry.file_name() == GENERATOR {
            continue;
        }
        let meta = fs::symlink_metadata(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let rel = path
            .strip_prefix(root)
            .ok()
            .and_then(Path::to_str)
            .ok_or_else(|| format!("{}: not a UTF-8 path", path.display()))?
            .to_string();
        if meta.is_dir() {
            scan_plain(root, &path, name, out)?;
        } else if meta.is_file() {
            out.insert(
                rel,
                Entry {
                    content: Content::Plain(path),
                    mode: meta.permissions().mode() & 0o777,
                    collection: name.to_string(),
                },
            );
        } else {
            return Err(format!(
                "`{rel}` is not a regular file (symlinks and special files are not allowed)"
            ));
        }
    }
    Ok(())
}

fn nix_instantiate_bin() -> std::ffi::OsString {
    std::env::var_os(NIX_INSTANTIATE_ENV).unwrap_or_else(|| "nix-instantiate".into())
}

/// Evaluate `<dir>/default.nix` to `path → (text, mode)`.
fn eval_generator(dir: &Path, guest_dir: &Path) -> Result<BTreeMap<String, (String, u32)>, String> {
    let out = Command::new(nix_instantiate_bin())
        .args(["--eval", "--strict", "--json", "--expr", EVAL_NIX])
        .arg("--argstr")
        .arg("collection")
        .arg(dir)
        .arg("--argstr")
        .arg("guestDir")
        .arg(guest_dir)
        .output()
        .map_err(|e| format!("running nix-instantiate for {}: {e}", dir.display()))?;
    if !out.status.success() {
        return Err(format!(
            "evaluating {}:\n{}",
            dir.join(GENERATOR).display(),
            String::from_utf8_lossy(&out.stderr).trim()
        ));
    }
    parse_generated(&out.stdout)
}

/// Parse the evaluator's JSON output. Pure.
fn parse_generated(json: &[u8]) -> Result<BTreeMap<String, (String, u32)>, String> {
    #[derive(serde::Deserialize)]
    struct Generated {
        text: String,
        mode: String,
    }
    let files: BTreeMap<String, Generated> =
        serde_json::from_slice(json).map_err(|e| format!("reading generated dotfiles: {e}"))?;
    files
        .into_iter()
        .map(|(path, f)| Ok((path, (f.text, parse_mode(&f.mode)?))))
        .collect()
}

/// Merge `collections` in order: a later collection's file replaces an earlier
/// one's, and each replacement is reported. Pure.
pub fn merge(collections: Vec<Collection>) -> Merged {
    let mut merged = Merged::default();
    for c in collections {
        for (path, entry) in c.files {
            if let Some(prev) = merged.files.get(&path) {
                merged.warnings.push(format!(
                    "dotfiles: {path} from '{}' replaced by '{}'",
                    prev.collection, entry.collection
                ));
            }
            merged.files.insert(path, entry);
        }
    }
    merged
}

/// Write `merged` to `dest` (0700), replacing it atomically: built next to it,
/// then renamed into place.
pub fn write_tree(merged: &Merged, dest: &Path) -> io::Result<()> {
    let tmp = dest.with_extension("tmp");
    paths::remove_dir_quiet(&tmp)?;
    fs::create_dir_all(&tmp)?;
    fs::set_permissions(&tmp, fs::Permissions::from_mode(0o700))?;
    for (path, entry) in &merged.files {
        let target = tmp.join(path);
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent)?;
        }
        match &entry.content {
            Content::Plain(src) => {
                fs::copy(src, &target)?;
            }
            Content::Text(text) => fs::write(&target, text)?,
        }
        fs::set_permissions(&target, fs::Permissions::from_mode(entry.mode))?;
    }
    paths::remove_dir_quiet(dest)?;
    fs::rename(&tmp, dest)
}

/// Copy the tree at `src` to `dst`, keeping the permission bits of files and
/// folders. Only regular files and folders are copied; anything else is an
/// error, as in a collection.
pub fn copy_tree(src: &Path, dst: &Path) -> io::Result<()> {
    let meta = fs::symlink_metadata(src)?;
    fs::create_dir_all(dst)?;
    fs::set_permissions(
        dst,
        fs::Permissions::from_mode(meta.permissions().mode() & 0o777),
    )?;
    for entry in fs::read_dir(src)? {
        let entry = entry?;
        let from = entry.path();
        let to = dst.join(entry.file_name());
        let ty = entry.file_type()?;
        if ty.is_dir() {
            copy_tree(&from, &to)?;
        } else if ty.is_file() {
            fs::copy(&from, &to)?;
        } else {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                format!("{}: not a regular file", from.display()),
            ));
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(name: &str) -> PathBuf {
        let d =
            std::env::temp_dir().join(format!("sodabox-dotfiles-{}-{name}", std::process::id()));
        let _ = fs::remove_dir_all(&d);
        fs::create_dir_all(&d).unwrap();
        d
    }

    fn write(path: &Path, text: &str, mode: u32) {
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, text).unwrap();
        fs::set_permissions(path, fs::Permissions::from_mode(mode)).unwrap();
    }

    fn no_eval(_: &Path) -> Result<BTreeMap<String, (String, u32)>, String> {
        panic!("no default.nix here")
    }

    #[test]
    fn paths_must_stay_under_root() {
        for ok in [".claude/settings.json", ".gitconfig", "a/b/c"] {
            assert!(validate_path(ok).is_ok(), "{ok}");
        }
        for bad in ["", "/etc/passwd", "../x", "a/../b", "a//b", "./a", "a/"] {
            assert!(validate_path(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn modes_are_octal_permission_bits() {
        assert_eq!(parse_mode("0600"), Ok(0o600));
        assert_eq!(parse_mode("644"), Ok(0o644));
        assert!(parse_mode("4755").is_err());
        assert!(parse_mode("0x1").is_err());
        assert!(parse_mode("").is_err());
    }

    #[test]
    fn loads_plain_files_with_their_modes() {
        let d = tmp("plain");
        write(&d.join(".claude/settings.json"), "{}", 0o644);
        write(&d.join(".aws/credentials"), "secret", 0o600);
        let c = load_from(&d, "c", no_eval).unwrap();
        let paths: Vec<_> = c.files.keys().cloned().collect();
        assert_eq!(paths, [".aws/credentials", ".claude/settings.json"]);
        assert_eq!(c.files[".aws/credentials"].mode, 0o600);
        assert_eq!(c.files[".claude/settings.json"].mode, 0o644);
        fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn rejects_symlinks_and_unknown_collections() {
        let d = tmp("link");
        std::os::unix::fs::symlink("/etc/passwd", d.join("passwd")).unwrap();
        let e = load_from(&d, "c", no_eval).unwrap_err();
        assert!(e.contains("not a regular file"), "{e}");
        let e = load_from(&d.join("missing"), "missing", no_eval).unwrap_err();
        assert!(e.contains("unknown dotfile collection 'missing'"), "{e}");
        fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn generated_files_join_plain_ones_but_may_not_collide() {
        let d = tmp("gen");
        write(&d.join(".a"), "plain", 0o644);
        write(
            &d.join(GENERATOR),
            "unused: the evaluator is stubbed",
            0o644,
        );
        let c = load_from(&d, "c", |_| {
            Ok(BTreeMap::from([(
                ".b".to_string(),
                ("gen".to_string(), 0o600),
            )]))
        })
        .unwrap();
        // default.nix itself is not a dotfile.
        assert_eq!(c.files.keys().cloned().collect::<Vec<_>>(), [".a", ".b"]);
        assert_eq!(c.files[".b"].content, Content::Text("gen".into()));

        let e = load_from(&d, "c", |_| {
            Ok(BTreeMap::from([(
                ".a".to_string(),
                ("gen".to_string(), 0o644),
            )]))
        })
        .unwrap_err();
        assert!(e.contains("both a plain file and generated"), "{e}");
        let e = load_from(&d, "c", |_| {
            Ok(BTreeMap::from([(
                "../x".to_string(),
                ("gen".to_string(), 0o644),
            )]))
        })
        .unwrap_err();
        assert!(e.contains("invalid dotfile path"), "{e}");
        fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn parses_evaluator_output() {
        let files = parse_generated(br#"{".x":{"text":"hi","mode":"0600"}}"#).unwrap();
        assert_eq!(files[".x"], ("hi".to_string(), 0o600));
        assert!(parse_generated(br#"{".x":{"text":"hi","mode":"9"}}"#).is_err());
    }

    fn collection(name: &str, files: &[(&str, &str)]) -> Collection {
        Collection {
            name: name.into(),
            files: files
                .iter()
                .map(|(p, t)| {
                    (
                        p.to_string(),
                        Entry {
                            content: Content::Text(t.to_string()),
                            mode: 0o644,
                            collection: name.into(),
                        },
                    )
                })
                .collect(),
        }
    }

    #[test]
    fn later_collections_win_with_a_warning() {
        let m = merge(vec![
            collection("a", &[(".x", "a"), (".y", "a")]),
            collection("b", &[(".x", "b")]),
        ]);
        assert_eq!(m.files[".x"].content, Content::Text("b".into()));
        assert_eq!(m.files[".y"].collection, "a");
        assert_eq!(m.warnings, ["dotfiles: .x from 'a' replaced by 'b'"]);
    }

    #[test]
    fn writes_and_copies_trees_with_modes() {
        let d = tmp("write");
        write(&d.join("src/.aws/credentials"), "secret", 0o600);
        let mut c = load_from(&d.join("src"), "src", no_eval).unwrap();
        c.files
            .extend(collection("gen", &[(".gitconfig", "[user]\n")]).files);
        let dest = d.join("dotfiles");
        write_tree(&merge(vec![collection("old", &[(".stale", "x")])]), &dest).unwrap();
        // Rewriting replaces the old tree.
        write_tree(&merge(vec![c]), &dest).unwrap();
        assert!(!dest.join(".stale").exists());

        let mode = |p: &Path| fs::metadata(p).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode(&dest), 0o700);
        assert_eq!(
            fs::read_to_string(dest.join(".aws/credentials")).unwrap(),
            "secret"
        );
        assert_eq!(mode(&dest.join(".aws/credentials")), 0o600);
        assert_eq!(
            fs::read_to_string(dest.join(".gitconfig")).unwrap(),
            "[user]\n"
        );
        assert!(!dest.with_extension("tmp").exists());

        let copy = d.join("copy");
        copy_tree(&dest, &copy).unwrap();
        assert_eq!(mode(&copy), 0o700);
        assert_eq!(mode(&copy.join(".aws/credentials")), 0o600);
        assert_eq!(
            fs::read_to_string(copy.join(".gitconfig")).unwrap(),
            "[user]\n"
        );
        fs::remove_dir_all(&d).unwrap();
    }
}
